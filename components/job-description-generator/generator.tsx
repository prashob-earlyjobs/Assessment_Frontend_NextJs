"use client";

import { useMemo, useState, type ReactNode } from "react";

type FormState = {
  jobTitle: string;
  industry: string;
  location: string;
  employmentType: string;
  shiftRequirements: string;
  rolePurpose: string;
  responsibilities: string;
  mandatoryQualifications: string;
  preferredSkills: string;
  workingConditions: string;
  salary: string;
  applicationProcess: string;
};

const industries = [
  "Manufacturing",
  "Healthcare",
  "Warehouse & Logistics",
  "Sales",
  "Administrative",
  "Other",
] as const;

const employmentTypes = [
  "Full-time",
  "Part-time",
  "Contract",
  "Temporary",
  "Internship",
] as const;

const defaults: FormState = {
  jobTitle: "Production Trainee",
  industry: "Manufacturing",
  location: "Pune, Maharashtra",
  employmentType: "Full-time",
  shiftRequirements: "Rotational shifts including night shifts as rostered",
  rolePurpose:
    "Support production line operations, follow standard work instructions and help maintain quality and safety standards on the shop floor.",
  responsibilities:
    "Follow daily production instructions under supervisor guidance\nOperate or assist with assigned machines after training\nMaintain workplace cleanliness and safety practices\nReport quality or equipment issues promptly\nComplete basic production records as required",
  mandatoryQualifications:
    "10th / 12th / ITI as applicable to the role\nWillingness to work in a manufacturing environment\nAbility to follow verbal and written instructions",
  preferredSkills:
    "Prior shop-floor exposure\nBasic understanding of quality checks",
  workingConditions:
    "Plant / factory environment with standing work and personal protective equipment as required",
  salary: "",
  applicationProcess:
    "Apply through the channel shared by the employer. Shortlisted candidates will be contacted for the next step.",
};

function linesToBullets(text: string) {
  return text
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);
}

function buildDocument(form: FormState) {
  const responsibilities = linesToBullets(form.responsibilities);
  const mandatory = linesToBullets(form.mandatoryQualifications);
  const preferred = linesToBullets(form.preferredSkills);

  const sections = [
    `# ${form.jobTitle || "Job Title"}`,
    "",
    "## Role overview",
    form.rolePurpose || "Add a short statement explaining why this role exists.",
    "",
    "## Position details",
    `- Industry: ${form.industry || "—"}`,
    `- Location: ${form.location || "—"}`,
    `- Employment type: ${form.employmentType || "—"}`,
    `- Shift / working hours: ${form.shiftRequirements || "—"}`,
    form.workingConditions ? `- Working conditions: ${form.workingConditions}` : null,
    form.salary.trim() ? `- Compensation: ${form.salary.trim()}` : null,
    "",
    "## Key responsibilities",
    ...(responsibilities.length
      ? responsibilities.map((item) => `- ${item}`)
      : ["- Add the main duties for this role."]),
    "",
    "## Mandatory qualifications",
    ...(mandatory.length
      ? mandatory.map((item) => `- ${item}`)
      : ["- Add mandatory eligibility requirements."]),
    "",
    "## Preferred skills",
    ...(preferred.length
      ? preferred.map((item) => `- ${item}`)
      : ["- Optional: list preferred skills separately from mandatory requirements."]),
    "",
    "## How to apply",
    form.applicationProcess || "Describe how candidates should apply and what happens next.",
    "",
    "_Draft generated by EarlyJobs Job Description Generator. Review for accuracy, clarity and legal compliance before publishing._",
  ].filter((line) => line !== null) as string[];

  return sections.join("\n");
}

function Field({
  id,
  label,
  hint,
  children,
}: {
  id: string;
  label: string;
  hint?: string;
  children: ReactNode;
}) {
  return (
    <label htmlFor={id} className="block">
      <span className="text-sm font-medium tracking-[-0.02em] text-neutral-950">{label}</span>
      <div className="mt-2">{children}</div>
      {hint ? (
        <span className="mt-1.5 block text-[12px] leading-5 text-neutral-500">{hint}</span>
      ) : null}
    </label>
  );
}

const inputClass =
  "w-full rounded-lg border border-black/10 bg-white px-3 py-2.5 text-sm text-neutral-950 outline-none transition-colors focus:border-[#2563EB] focus:ring-2 focus:ring-[#2563EB]/15";

export function JobDescriptionGenerator() {
  const [form, setForm] = useState<FormState>(defaults);
  const [draft, setDraft] = useState(() => buildDocument(defaults));
  const [editing, setEditing] = useState(false);
  const [copied, setCopied] = useState(false);
  const [generated, setGenerated] = useState(true);

  const previewLines = useMemo(() => draft.split("\n"), [draft]);

  function update<K extends keyof FormState>(key: K, value: FormState[K]) {
    setForm((prev) => ({ ...prev, [key]: value }));
  }

  function generate() {
    const next = buildDocument(form);
    setDraft(next);
    setEditing(false);
    setGenerated(true);
  }

  async function copyDraft() {
    try {
      await navigator.clipboard.writeText(draft);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 2000);
    } catch {
      setCopied(false);
    }
  }

  function downloadDraft() {
    const blob = new Blob([draft], { type: "text/plain;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement("a");
    const slug = (form.jobTitle || "job-description")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/(^-|-$)/g, "");
    anchor.href = url;
    anchor.download = `earlyjobs-${slug || "job-description"}.txt`;
    anchor.click();
    URL.revokeObjectURL(url);
  }

  return (
    <div className="overflow-hidden rounded-2xl border border-black/10 bg-white shadow-[0_24px_80px_rgba(15,23,42,0.06)]">
      <div className="flex flex-wrap items-center justify-between gap-3 border-b border-black/5 bg-[#f8fafc] px-5 py-4 sm:px-6">
        <div>
          <p className="text-[11px] font-semibold tracking-[0.14em] text-[#2563EB] uppercase">
            Template-based draft
          </p>
          <h3 className="mt-1 text-base font-semibold tracking-[-0.02em]">
            Job Description Generator
          </h3>
        </div>
        <button
          type="button"
          onClick={() => {
            setForm(defaults);
            setDraft(buildDocument(defaults));
            setEditing(false);
            setGenerated(true);
          }}
          className="rounded-lg border border-black/10 bg-white px-3 py-1.5 text-[12px] font-medium text-neutral-700 transition-colors hover:bg-neutral-50"
        >
          Reset sample
        </button>
      </div>

      <div className="grid lg:grid-cols-2">
        <div className="border-b border-black/5 p-5 sm:p-6 lg:border-r lg:border-b-0">
          <div className="grid gap-4">
            <Field id="job-title" label="Job title" hint="Use a recognisable title for the actual position.">
              <input
                id="job-title"
                className={inputClass}
                value={form.jobTitle}
                onChange={(event) => update("jobTitle", event.target.value)}
              />
            </Field>

            <div className="grid gap-4 sm:grid-cols-2">
              <Field id="industry" label="Industry">
                <select
                  id="industry"
                  className={inputClass}
                  value={form.industry}
                  onChange={(event) => update("industry", event.target.value)}
                >
                  {industries.map((item) => (
                    <option key={item} value={item}>
                      {item}
                    </option>
                  ))}
                </select>
              </Field>
              <Field id="employment-type" label="Employment type">
                <select
                  id="employment-type"
                  className={inputClass}
                  value={form.employmentType}
                  onChange={(event) => update("employmentType", event.target.value)}
                >
                  {employmentTypes.map((item) => (
                    <option key={item} value={item}>
                      {item}
                    </option>
                  ))}
                </select>
              </Field>
            </div>

            <Field id="location" label="Location">
              <input
                id="location"
                className={inputClass}
                value={form.location}
                onChange={(event) => update("location", event.target.value)}
              />
            </Field>

            <Field id="shifts" label="Shift requirements">
              <input
                id="shifts"
                className={inputClass}
                value={form.shiftRequirements}
                onChange={(event) => update("shiftRequirements", event.target.value)}
              />
            </Field>

            <Field id="role-purpose" label="Role purpose">
              <textarea
                id="role-purpose"
                rows={3}
                className={inputClass}
                value={form.rolePurpose}
                onChange={(event) => update("rolePurpose", event.target.value)}
              />
            </Field>

            <Field
              id="responsibilities"
              label="Responsibilities"
              hint="One responsibility per line."
            >
              <textarea
                id="responsibilities"
                rows={5}
                className={inputClass}
                value={form.responsibilities}
                onChange={(event) => update("responsibilities", event.target.value)}
              />
            </Field>

            <Field
              id="mandatory"
              label="Mandatory qualifications"
              hint="One requirement per line. Keep preferred skills separate."
            >
              <textarea
                id="mandatory"
                rows={4}
                className={inputClass}
                value={form.mandatoryQualifications}
                onChange={(event) => update("mandatoryQualifications", event.target.value)}
              />
            </Field>

            <Field id="preferred" label="Preferred skills" hint="One skill per line.">
              <textarea
                id="preferred"
                rows={3}
                className={inputClass}
                value={form.preferredSkills}
                onChange={(event) => update("preferredSkills", event.target.value)}
              />
            </Field>

            <Field id="conditions" label="Working conditions">
              <textarea
                id="conditions"
                rows={2}
                className={inputClass}
                value={form.workingConditions}
                onChange={(event) => update("workingConditions", event.target.value)}
              />
            </Field>

            <Field
              id="salary"
              label="Compensation (optional)"
              hint="Only enter approved salary information. The tool will not invent ranges."
            >
              <input
                id="salary"
                className={inputClass}
                value={form.salary}
                placeholder="Leave blank if not approved for publication"
                onChange={(event) => update("salary", event.target.value)}
              />
            </Field>

            <Field id="apply" label="Application process">
              <textarea
                id="apply"
                rows={2}
                className={inputClass}
                value={form.applicationProcess}
                onChange={(event) => update("applicationProcess", event.target.value)}
              />
            </Field>

            <button
              type="button"
              onClick={generate}
              className="inline-flex h-11 items-center justify-center rounded-[6px] bg-brand px-4 text-[13px] font-medium text-white transition-[border-radius,background-color] duration-500 ease-in-out hover:rounded-[22px] hover:bg-[#d85c42]"
            >
              Generate Job Description
            </button>
          </div>
        </div>

        <div className="bg-[#f8fafc] p-5 sm:p-6">
          <div className="flex flex-wrap items-center justify-between gap-3">
            <div>
              <p className="text-[11px] font-medium tracking-[0.08em] text-neutral-400 uppercase">
                Live document preview
              </p>
              <p className="mt-1 text-sm text-neutral-600">
                {generated
                  ? "Editable structured draft from your inputs"
                  : "Fill the form and generate a draft"}
              </p>
            </div>
            <div className="flex flex-wrap gap-2">
              <button
                type="button"
                onClick={() => setEditing((value) => !value)}
                className="rounded-lg border border-black/10 bg-white px-3 py-2 text-[12px] font-medium text-neutral-700 transition-colors hover:bg-neutral-50"
              >
                {editing ? "Preview" : "Edit draft"}
              </button>
              <button
                type="button"
                onClick={copyDraft}
                className="rounded-lg border border-black/10 bg-white px-3 py-2 text-[12px] font-medium text-neutral-700 transition-colors hover:bg-neutral-50"
              >
                {copied ? "Copied" : "Copy"}
              </button>
              <button
                type="button"
                onClick={downloadDraft}
                className="rounded-lg border border-black/10 bg-white px-3 py-2 text-[12px] font-medium text-neutral-700 transition-colors hover:bg-neutral-50"
              >
                Download
              </button>
            </div>
          </div>

          <div className="mt-4 min-h-[28rem] rounded-xl border border-black/5 bg-white p-4 sm:p-5">
            {editing ? (
              <textarea
                value={draft}
                onChange={(event) => setDraft(event.target.value)}
                className="h-[28rem] w-full resize-y rounded-lg border border-black/10 bg-[#f8fafc] px-3 py-3 font-mono text-[12px] leading-5 text-neutral-800 outline-none focus:border-[#2563EB]"
              />
            ) : (
              <div className="space-y-1 font-mono text-[12px] leading-5 text-neutral-700 sm:text-[13px]">
                {previewLines.map((line, index) => {
                  if (line.startsWith("# ")) {
                    return (
                      <p
                        key={`${index}-${line}`}
                        className="pt-1 font-sans text-xl font-semibold tracking-[-0.03em] text-neutral-950"
                      >
                        {line.replace(/^#\s*/, "")}
                      </p>
                    );
                  }
                  if (line.startsWith("## ")) {
                    return (
                      <p
                        key={`${index}-${line}`}
                        className="pt-4 font-sans text-sm font-semibold tracking-[-0.02em] text-neutral-950"
                      >
                        {line.replace(/^##\s*/, "")}
                      </p>
                    );
                  }
                  if (line.startsWith("- ")) {
                    return (
                      <p key={`${index}-${line}`} className="pl-2">
                        • {line.replace(/^-\s*/, "")}
                      </p>
                    );
                  }
                  if (line.startsWith("_") && line.endsWith("_")) {
                    return (
                      <p key={`${index}-${line}`} className="pt-4 font-sans text-[12px] text-neutral-500">
                        {line.replace(/^_|_$/g, "")}
                      </p>
                    );
                  }
                  if (!line) {
                    return <div key={`${index}-space`} className="h-2" />;
                  }
                  return (
                    <p key={`${index}-${line}`} className="font-sans text-sm leading-6 text-neutral-600">
                      {line}
                    </p>
                  );
                })}
              </div>
            )}
          </div>

          <p className="mt-4 text-[12px] leading-5 text-neutral-500">
            This is a template-based organiser, not an AI writer. It only uses the information you
            enter and will not invent salary ranges, certifications or benefits.
          </p>
        </div>
      </div>
    </div>
  );
}
